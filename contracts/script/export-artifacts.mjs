#!/usr/bin/env node
/**
 * Copies the compiled contract interfaces into the TypeScript protocol package, so the gateway
 * and the web app call the contracts through exactly the ABIs Foundry tested.
 *
 *   cd contracts && forge build && node script/export-artifacts.mjs
 *
 * Output: packages/protocol/src/hedera/generated.ts (committed).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, '../out');
const target = resolve(here, '../../packages/protocol/src/hedera/generated.ts');

/** [file, contract, export name, include bytecode] */
const contracts = [
  ['CustodyOracle.sol', 'CustodyOracle', 'custodyOracle', true],
  ['ReceiptMarket.sol', 'ReceiptMarket', 'receiptMarket', true],
  ['IAtsFactory.sol', 'IAtsFactory', 'atsFactory', false],
  ['IAtsFactory.sol', 'IAtsResolver', 'atsResolver', false],
  ['IAtsToken.sol', 'IAtsToken', 'atsToken', false],
];

let source =
  '// GENERATED by contracts/script/export-artifacts.mjs from the Foundry build. Do not edit.\n' +
  '// Regenerate: cd contracts && forge build && node script/export-artifacts.mjs\n\n';

for (const [file, contract, name, withBytecode] of contracts) {
  const artifact = JSON.parse(readFileSync(resolve(out, file, `${contract}.json`), 'utf8'));
  source += `export const ${name}Abi = ${JSON.stringify(artifact.abi)} as const;\n\n`;
  if (withBytecode) {
    const bytecode = artifact.bytecode.object;
    if (!/^0x[0-9a-f]+$/.test(bytecode)) throw new Error(`${contract}: bytecode has unlinked libraries`);
    source += `export const ${name}Bytecode = '${bytecode}' as const;\n\n`;
  }
}

writeFileSync(target, source);
console.log(`Wrote ${target} (${source.length} bytes)`);

/**
 * Recompiles the dev engine and refreshes `engine.artifact.json`, the checked-in bytecode the
 * devnet installs. Only needed after editing packages/devnet/contracts/src/ArkivDevEngine.sol;
 * running the devnet never needs Foundry's compiler, only anvil.
 *
 * Usage: pnpm --filter @pinky/devnet build:arkiv-engine
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const project = resolve(here, '../../contracts');
const source = resolve(project, 'src/ArkivDevEngine.sol');
const output = resolve(here, 'engine.artifact.json');

execFileSync('forge', ['build', '--root', project], { stdio: 'inherit' });

const built = JSON.parse(
  readFileSync(resolve(project, 'out/ArkivDevEngine.sol/ArkivDevEngine.json'), 'utf8'),
);
const settings = built.metadata?.settings ?? {};
const artifact = {
  note: 'Generated by build-engine.ts from packages/devnet/contracts/src/ArkivDevEngine.sol. Do not edit.',
  contract: 'ArkivDevEngine',
  solc: built.metadata?.compiler?.version,
  evmVersion: settings.evmVersion,
  optimizerRuns: settings.optimizer?.runs,
  viaIR: settings.viaIR ?? false,
  sourceSha256: createHash('sha256').update(readFileSync(source)).digest('hex'),
  deployedBytecode: built.deployedBytecode.object as string,
};
if (!/^0x[0-9a-f]+$/.test(artifact.deployedBytecode)) {
  throw new Error('the engine bytecode is not plain hex (unlinked library or immutable?)');
}
writeFileSync(output, `${JSON.stringify(artifact, null, 2)}\n`);
console.log(`Wrote ${output} (${(artifact.deployedBytecode.length - 2) / 2} bytes, solc ${artifact.solc})`);
